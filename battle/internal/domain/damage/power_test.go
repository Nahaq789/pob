package damage

import "testing"

func TestPower_final(t *testing.T) {
	tests := []struct {
		name  string
		power Power
		want  int
	}{
		// ── 単一補正（弱化） ──
		{
			name:  "どろあそび/みずあそび(1352): 100*1352/4096≈33",
			power: NewPower(100, 1352),
			want:  33,
		},
		{
			name:  "たいねつ/ソーラービーム/ソーラーブレード/フィールド弱化(2048): 100*2048/4096=50",
			power: NewPower(100, 2048),
			want:  50,
		},
		{
			name:  "オーラブレイク/とうそうしん(異性)(3072): 100*3072/4096=75",
			power: NewPower(100, 3072),
			want:  75,
		},

		// ── 単一補正（強化） ──
		{
			name:  "ちからのハチマキ/ものしりメガネ(4505): 100*4505/4096≈110",
			power: NewPower(100, 4505),
			want:  110,
		},
		{
			name:  "スキン系特性7~/プレート/シルクのスカーフ/てつのこぶし/こんごうだま/しらたま/はっきんだま/こころのしずく7~(4915): 100*4915/4096≈120",
			power: NewPower(100, 4915),
			want:  120,
		},
		{
			name:  "とうそうしん(同性)/かんそうはだ(5120): 100*5120/4096=125",
			power: NewPower(100, 5120),
			want:  125,
		},
		{
			name:  "バッテリー/パワースポット/アナライズ/かたいツメ/スキン系特性6/ちからずく/ジュエル6~/フィールド強化8(5325): 100*5325/4096≈130",
			power: NewPower(100, 5325),
			want:  130,
		},
		{
			name:  "ダークオーラ/フェアリーオーラ(5448): 100*5448/4096≈133",
			power: NewPower(100, 5448),
			want:  133,
		},
		{
			name:  "テクニシャン/がんじょうあご/すてみ/どくぼうそう/ねつぼうそう/はがねのせいしん/メガランチャー/パンクロック/すなのちから/からげんき/ジュエル5/Gのちから/はたきおとす6~/ミストバースト/ワイドフォース/てだすけ/さきどり/フィールド強化~7(6144): 100*6144/4096=150",
			power: NewPower(100, 6144),
			want:  150,
		},
		{
			name:  "じゅうでん/うっぷんばらし/かたきうち/クロスサンダー/クロスフレイム/しおみず/ベノムショック(8192): 100*8192/4096=200",
			power: NewPower(100, 8192),
			want:  200,
		},

		// ── 複数補正（累積計算） ──
		{
			name:  "テクニシャン(6144)+ちからのハチマキ(4505): 累積6757.5→五捨6757, 60*6757/4096=99",
			power: NewPower(60, 6144, 4505),
			want:  99,
		},
		{
			name:  "ダークオーラ(5448)+はたきおとす補正(6144): wiki例 65*8172/4096=130",
			power: NewPower(65, 5448, 6144),
			want:  130,
		},
		{
			name:  "じゅうでん(8192)+テクニシャン(6144): 累積12288, 40*12288/4096=120",
			power: NewPower(40, 8192, 6144),
			want:  120,
		},
		{
			name:  "たいねつ弱化(2048)+テクニシャン強化(6144): 累積3072, 60*3072/4096=45",
			power: NewPower(60, 2048, 6144),
			want:  45,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := tt.power.final()
			if got != tt.want {
				t.Errorf("final() = %v, want %v", got, tt.want)
			}
		})
	}
}
